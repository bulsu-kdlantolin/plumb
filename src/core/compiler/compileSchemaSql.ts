import type { EntityFieldSpec, EntitySpec, ProjectSpec } from '../../types/spec.types'

const quoteIdentifier = (value: string) => `"${value.replace(/"/g, '""')}"`
const sqlType = (type: string) => /^[A-Za-z][A-Za-z0-9_]*(\s*\([0-9 ,]+\))?$/.test(type) ? type : 'TEXT'
const safeName = (value: string) => value.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'policy'

function indexColumns(index: string, entity: EntitySpec): string[] {
  const candidate = index.replace(new RegExp(`^${entity.name}_?`, 'i'), '').replace(/_(idx|key|unique)$/i, '').toLowerCase()
  const fields = entity.fields.filter((field) => {
    const normalized = field.name.toLowerCase()
    const aliases = [normalized, normalized.replace(/_(id|at|key)$/, '')]
    return aliases.some((alias) => alias && new RegExp(`(^|_)${alias.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(_|$)`, 'i').test(candidate))
  })
  if (fields.length) return fields.map((field) => field.name)
  const exact = entity.fields.find((field) => field.name.toLowerCase() === index.toLowerCase())
  const fallback = exact ?? entity.fields.find((field) => field.isPrimary) ?? entity.fields[0]
  return fallback ? [fallback.name] : []
}

function fieldSql(field: EntityFieldSpec, entities: EntitySpec[]): string {
  let declaration = `  ${quoteIdentifier(field.name)} ${sqlType(field.type)}`
  if (field.isPrimary) declaration += ' PRIMARY KEY'
  if (!field.isNullable) declaration += ' NOT NULL'
  if (field.references) {
    const target = entities.find((entity) => entity.name === field.references?.entity)
    const targetField = target?.fields.find((candidate) => candidate.name === field.references?.field)
    if (target && targetField) declaration += ` REFERENCES ${quoteIdentifier(target.name)} (${quoteIdentifier(targetField.name)}) ON DELETE ${(field.onDelete ?? 'restrict').toUpperCase().replace('-', ' ')}`
  }
  return declaration
}

export function compileSchemaSql(project: ProjectSpec): string {
  const out = ['-- Generated by Plumb. Review RLS predicates before applying.', '']
  for (const entity of project.data.entities) {
    out.push(`CREATE TABLE IF NOT EXISTS ${quoteIdentifier(entity.name)} (`)
    const fields = entity.fields.map((field) => fieldSql(field, project.data.entities))
    if (!fields.some((field) => field.includes('PRIMARY KEY'))) fields.unshift('  "id" UUID PRIMARY KEY DEFAULT gen_random_uuid()')
    out.push(fields.join(',\n'), ');', '')
    for (const index of entity.indexes) {
      const indexName = safeName(index)
      const columns = indexColumns(index, entity)
      if (columns.length) out.push(`CREATE INDEX IF NOT EXISTS ${quoteIdentifier(indexName)} ON ${quoteIdentifier(entity.name)} (${columns.map(quoteIdentifier).join(', ')});`)
    }
    out.push(`ALTER TABLE ${quoteIdentifier(entity.name)} ENABLE ROW LEVEL SECURITY;`)
    if (entity.rlsPolicy.trim()) {
      const policyName = `${safeName(entity.name)}_member_access`
      out.push(`CREATE POLICY ${quoteIdentifier(policyName)} ON ${quoteIdentifier(entity.name)} FOR ALL USING (${entity.rlsPolicy.trim()}) WITH CHECK (${entity.rlsPolicy.trim()});`)
    }
    out.push('')
  }
  return `${out.join('\n').trimEnd()}\n`
}
